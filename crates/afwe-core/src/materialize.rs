//! Phase 3: Preview-First Tripwire Materializer, BLAKE3 Manifest & Base-Branch Verification.
//!
//! `afwe materialize` is preview-first and opt-in:
//! - Running `afwe materialize` without `--apply`, `--remove`, or `--check` previews all planned
//!   files and marker blocks without touching disk.
//! - `--apply` writes the selected layers and records BLAKE3 hashes in `.afwe/guardrails/manifest.yaml`.
//! - `--remove` cleanly removes materialized files and marker blocks without clobbering user hooks.
//! - `--check [--base <ref>]` verifies local BLAKE3 integrity and compares protected guards against
//!   `<ref>` via `git show <ref>:...` so an agent cannot tamper with a rule and its manifest hash together.

use crate::contract;
use crate::engine::Engine;
use crate::onboard::CI_TEMPLATE;
use crate::store::{parse_yaml, to_yaml};
use crate::util::{hash_bytes, now};
use anyhow::Result;
use serde::{Deserialize, Serialize};
use serde_json::{json, Value};
use std::collections::BTreeMap;
use std::path::Path;
use std::process::Command;

const CHAIN_BEGIN: &str = "# afwe-chain:begin";
const CHAIN_END: &str = "# afwe-chain:end";
const AGENTS_BEGIN: &str = "<!-- afwe:begin -->";
const AGENTS_END: &str = "<!-- afwe:end -->";

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct MaterializeOptions {
    pub apply: bool,
    pub remove: bool,
    pub check: bool,
    pub base: Option<String>,
    pub native_tests: bool,
    pub git_hooks: bool,
    pub ci: bool,
    pub claude_hooks: bool,
    pub agents_md: bool,
}

impl MaterializeOptions {
    pub fn effective_layers(&self) -> (bool, bool, bool, bool, bool) {
        let any_explicit = self.native_tests || self.git_hooks || self.ci || self.claude_hooks || self.agents_md;
        if any_explicit {
            (self.native_tests, self.git_hooks, self.ci, self.claude_hooks, self.agents_md)
        } else {
            // Default layers when none specified (claude_hooks is always opt-in)
            (true, true, true, false, true)
        }
    }
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct GuardrailManifest {
    pub version: u32,
    pub generated_at: String,
    #[serde(default)]
    pub entries: BTreeMap<String, String>,
}

pub const MANIFEST_REL_PATH: &str = ".afwe/guardrails/manifest.yaml";

pub fn run(engine: &Engine, opts: MaterializeOptions) -> Result<Value> {
    if opts.check {
        return check_manifest(engine, opts.base.as_deref());
    }
    if opts.remove {
        return remove_all(engine);
    }

    let root = &engine.store.project_root;
    let m = engine.store.manifest()?;
    let (native_tests, git_hooks, ci, claude_hooks, agents_md) = opts.effective_layers();

    let mut planned: BTreeMap<String, String> = BTreeMap::new();
    let mut actions: Vec<String> = Vec::new();

    if native_tests {
        let checks = engine.store.checks().unwrap_or_default();
        let pins = engine.store.pins().unwrap_or_default();
        let script = format!(
            "#!/usr/bin/env sh\n# Generated by `afwe materialize` — deterministic architectural tripwire runner.\n# Active pins: {} | Registered checks: {}\nset -e\nafwe gate --ci\n",
            pins.iter().filter(|p| p.status == "active").count(),
            checks.iter().filter(|c| c.status == "active").count()
        );
        planned.insert(".afwe/guardrails/generated_checks_test.sh".into(), script);
        actions.push("layer `native-tests`: .afwe/guardrails/generated_checks_test.sh".into());
    }

    if git_hooks {
        let hook_script = "#!/usr/bin/env sh\n# Generated by `afwe materialize`\nafwe gate --ci\n";
        planned.insert(".afwe/guardrails/pre-commit".into(), hook_script.to_string());
        actions.push("layer `git-hooks`: .afwe/guardrails/pre-commit (chained into existing git hook path)".into());
    }

    if ci {
        planned.insert(".github/workflows/afwe-gate.yml".into(), CI_TEMPLATE.to_string());
        actions.push("layer `ci`: .github/workflows/afwe-gate.yml (fetch-depth: 0 + base ref check)".into());
    }

    if claude_hooks {
        let settings = json!({
            "hooks": {
                "PostToolUse": [
                    {
                        "matcher": "Write|Edit|MultiEdit",
                        "hooks": [
                            {
                                "type": "command",
                                "command": "afwe verify"
                            }
                        ]
                    }
                ]
            }
        });
        planned.insert(
            ".afwe/guardrails/claude-hooks.json".into(),
            serde_json::to_string_pretty(&settings)?,
        );
        actions.push("layer `claude-hooks`: .afwe/guardrails/claude-hooks.json (notify_and_backup mode)".into());
    }

    if agents_md {
        let contracts = engine.store.contracts().unwrap_or_default();
        let block = contract::render_agents_block(&m.project.name, &contracts);
        planned.insert(".afwe/guardrails/agents-block.md".into(), block);
        actions.push("layer `agents-md`: AGENTS.md marker block".into());
    }

    if !opts.apply {
        let preview_files: Vec<Value> = planned
            .iter()
            .map(|(path, content)| {
                json!({
                    "path": path,
                    "blake3": hash_bytes(content.as_bytes()),
                    "bytes": content.len(),
                })
            })
            .collect();
        return Ok(json!({
            "status": "preview",
            "applied": false,
            "actions": actions,
            "files": preview_files,
            "next": "Run `afwe materialize --apply` to write these tripwires and `.afwe/guardrails/manifest.yaml`.",
        }));
    }

    // Apply requested layers
    let mut manifest_entries: BTreeMap<String, String> = BTreeMap::new();
    for (rel_path, content) in &planned {
        let abs = root.join(rel_path);
        if let Some(parent) = abs.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&abs, content)?;
        manifest_entries.insert(rel_path.clone(), hash_bytes(content.as_bytes()));
    }

    if git_hooks {
        chain_git_pre_commit(root)?;
    }

    if agents_md {
        if let Some(block) = planned.get(".afwe/guardrails/agents-block.md") {
            write_agents_marker_block(&root.join("AGENTS.md"), block)?;
        }
    }

    let manifest = GuardrailManifest {
        version: 1,
        generated_at: now(),
        entries: manifest_entries.clone(),
    };
    let manifest_yaml = to_yaml(&manifest)?;
    let manifest_abs = root.join(MANIFEST_REL_PATH);
    if let Some(parent) = manifest_abs.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(&manifest_abs, &manifest_yaml)?;

    engine.log(
        "human:materialize",
        "materialize_apply",
        format!("Materialized {} tripwire file(s)", manifest_entries.len()),
        Some(json!({"files": manifest_entries.keys().collect::<Vec<_>>()})),
    )?;

    Ok(json!({
        "status": "applied",
        "applied": true,
        "manifest": MANIFEST_REL_PATH,
        "actions": actions,
        "entries": manifest_entries,
    }))
}

/// Saves a quarantine copy of a file under `.afwe/state/quarantine/<turn_or_ts>/<rel_path>`
/// so no human concurrent edit is ever destroyed by a rollback or hook.
pub fn save_quarantine_backup(root: &Path, label: &str, rel_path: &str) -> Result<Option<String>> {
    let src = root.join(rel_path);
    if !src.is_file() {
        return Ok(None);
    }
    let safe_label: String = label
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '-' || c == '_' { c } else { '_' })
        .collect();
    let dest_rel = format!(".afwe/state/quarantine/{safe_label}/{rel_path}");
    let dest_abs = root.join(&dest_rel);
    if let Some(parent) = dest_abs.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::copy(&src, &dest_abs)?;
    Ok(Some(dest_rel))
}

fn resolve_git_hooks_dir(root: &Path) -> Option<std::path::PathBuf> {
    if root.join(".husky").is_dir() {
        return Some(root.join(".husky"));
    }
    if let Ok(out) = Command::new("git").args(["config", "--get", "core.hooksPath"]).current_dir(root).output() {
        if out.status.success() {
            let custom = String::from_utf8_lossy(&out.stdout).trim().to_string();
            if !custom.is_empty() {
                let p = Path::new(&custom);
                return Some(if p.is_absolute() { p.to_path_buf() } else { root.join(p) });
            }
        }
    }
    let git_hooks = root.join(".git/hooks");
    if git_hooks.is_dir() || root.join(".git").exists() {
        return Some(git_hooks);
    }
    None
}

fn chain_git_pre_commit(root: &Path) -> Result<()> {
    let Some(hooks_dir) = resolve_git_hooks_dir(root) else {
        return Ok(());
    };
    std::fs::create_dir_all(&hooks_dir)?;
    let hook_file = hooks_dir.join("pre-commit");
    let chain_block = format!(
        "{CHAIN_BEGIN}\nif [ -f \".afwe/guardrails/pre-commit\" ]; then\n  sh .afwe/guardrails/pre-commit || exit 1\nfi\n{CHAIN_END}"
    );
    if let Ok(existing) = std::fs::read_to_string(&hook_file) {
        let updated = match (existing.find(CHAIN_BEGIN), existing.find(CHAIN_END)) {
            (Some(a), Some(b)) if b > a => {
                format!("{}{}{}", &existing[..a], chain_block, &existing[b + CHAIN_END.len()..])
            }
            _ => format!("{}\n\n{}\n", existing.trim_end(), chain_block),
        };
        std::fs::write(&hook_file, updated)?;
    } else {
        std::fs::write(&hook_file, format!("#!/usr/bin/env sh\n{chain_block}\n"))?;
    }
    Ok(())
}

fn unchain_git_pre_commit(root: &Path) -> Result<bool> {
    let Some(hooks_dir) = resolve_git_hooks_dir(root) else {
        return Ok(false);
    };
    let hook_file = hooks_dir.join("pre-commit");
    let Ok(existing) = std::fs::read_to_string(&hook_file) else {
        return Ok(false);
    };
    if let (Some(a), Some(b)) = (existing.find(CHAIN_BEGIN), existing.find(CHAIN_END)) {
        if b > a {
            let rest = format!("{}{}", &existing[..a], &existing[b + CHAIN_END.len()..]);
            let trimmed = rest.trim();
            if trimmed.is_empty() || trimmed == "#!/usr/bin/env sh" || trimmed == "#!/bin/sh" {
                let _ = std::fs::remove_file(&hook_file);
            } else {
                std::fs::write(&hook_file, format!("{trimmed}\n"))?;
            }
            return Ok(true);
        }
    }
    Ok(false)
}

fn write_agents_marker_block(path: &Path, block: &str) -> Result<()> {
    if let Ok(existing) = std::fs::read_to_string(path) {
        if existing.contains("# AFWE-Core") {
            return Ok(());
        }
        let body = if block.contains(AGENTS_BEGIN) {
            block.to_string()
        } else {
            format!("{AGENTS_BEGIN}\n{block}\n{AGENTS_END}")
        };
        let next = match (existing.find(AGENTS_BEGIN), existing.find(AGENTS_END)) {
            (Some(a), Some(b)) if b > a => format!("{}{}{}", &existing[..a], body, &existing[b + AGENTS_END.len()..]),
            _ => format!("{}\n\n{}\n", existing.trim_end(), body),
        };
        std::fs::write(path, next)?;
    } else {
        let body = if block.contains(AGENTS_BEGIN) {
            block.to_string()
        } else {
            format!("{AGENTS_BEGIN}\n{block}\n{AGENTS_END}")
        };
        std::fs::write(path, format!("{body}\n"))?;
    }
    Ok(())
}

pub fn remove_all(engine: &Engine) -> Result<Value> {
    let root = &engine.store.project_root;
    let mut removed: Vec<String> = Vec::new();

    if let Ok(Some(text)) = engine.store.read_text("guardrails/manifest.yaml") {
        if let Ok(manifest) = parse_yaml::<GuardrailManifest>(&text) {
            for rel_path in manifest.entries.keys() {
                let abs = root.join(rel_path);
                if abs.is_file() {
                    let _ = std::fs::remove_file(&abs);
                    removed.push(rel_path.clone());
                }
            }
        }
    }
    let manifest_abs = root.join(MANIFEST_REL_PATH);
    if manifest_abs.is_file() {
        let _ = std::fs::remove_file(&manifest_abs);
        removed.push(MANIFEST_REL_PATH.to_string());
    }
    if unchain_git_pre_commit(root).unwrap_or(false) {
        removed.push("git pre-commit chain block".into());
    }

    engine.log(
        "human:materialize",
        "materialize_remove",
        format!("Removed {} materialized tripwire item(s)", removed.len()),
        Some(json!({"removed": removed})),
    )?;

    Ok(json!({
        "status": "removed",
        "removed": removed,
    }))
}

fn git_commit_exists(root: &Path, rev: &str) -> bool {
    Command::new("git")
        .args(["cat-file", "-e", &format!("{rev}^{{commit}}")])
        .current_dir(root)
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false)
}

fn git_show_file(root: &Path, rev: &str, rel_path: &str) -> Option<String> {
    let spec = format!("{rev}:{rel_path}");
    Command::new("git")
        .args(["show", &spec])
        .current_dir(root)
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).into_owned())
}

pub fn check_manifest(engine: &Engine, base_ref: Option<&str>) -> Result<Value> {
    let root = &engine.store.project_root;
    let mut failures: Vec<String> = Vec::new();
    let mut checked_files = 0usize;

    let manifest_abs = root.join(MANIFEST_REL_PATH);
    if manifest_abs.is_file() {
        let text = std::fs::read_to_string(&manifest_abs)?;
        let manifest: GuardrailManifest = parse_yaml(&text)?;
        for (rel_path, expected_hash) in &manifest.entries {
            checked_files += 1;
            let abs = root.join(rel_path);
            match std::fs::read(&abs) {
                Ok(bytes) => {
                    let actual_hash = hash_bytes(&bytes);
                    if &actual_hash != expected_hash {
                        failures.push(format!(
                            "TAMPER_DETECTED: `{rel_path}` hash mismatch (expected {expected_hash}, got {actual_hash})"
                        ));
                    }
                }
                Err(_) => {
                    failures.push(format!("MISSING_TRIPWIRE: `{rel_path}` listed in manifest is missing on disk"));
                }
            }
        }
    }

    if let Some(raw_base) = base_ref.map(str::trim).filter(|s| !s.is_empty()) {
        // Ignore all-zero SHA on initial branch push
        let is_zero_sha = raw_base.chars().all(|c| c == '0');
        if !is_zero_sha {
            if !git_commit_exists(root, raw_base) {
                let in_ci = std::env::var("CI")
                    .map(|v| !v.trim().is_empty() && v != "0" && !v.eq_ignore_ascii_case("false"))
                    .unwrap_or(false);
                if in_ci {
                    let _ = Command::new("git")
                        .args(["fetch", "origin", raw_base, "--depth=1"])
                        .current_dir(root)
                        .output();
                }
                if !git_commit_exists(root, raw_base) {
                    failures.push(format!(
                        "BASE_REF_MISSING: git ref `{raw_base}` is not present in the local git object database. Run `git fetch origin {raw_base} --depth=1` (or set `fetch-depth: 0` in actions/checkout) and re-run `afwe materialize --check --base {raw_base}`."
                    ));
                }
            }

            if git_commit_exists(root, raw_base) {
                // Compare base constraints against working tree constraints
                if let Some(base_constraints_yaml) = git_show_file(root, raw_base, ".afwe/blueprint/constraints.yaml") {
                    if let Ok(base_cs) = parse_yaml::<crate::model::Constraints>(&base_constraints_yaml) {
                        let cur_cs = engine.store.constraints().unwrap_or_default();
                        let approved_escalations: Vec<String> = crate::escalation::list(engine)
                            .unwrap_or_default()
                            .into_iter()
                            .filter(|e| e.status == "approved")
                            .map(|e| e.op)
                            .collect();
                        for bc in &base_cs.constraints {
                            if bc.phase.as_deref() == Some("planned") {
                                continue;
                            }
                            let still_present = cur_cs.constraints.iter().any(|c| {
                                c.id == bc.id && c.rule == bc.rule && c.from == bc.from && c.to == bc.to && c.severity == bc.severity
                            });
                            if !still_present && !approved_escalations.iter().any(|op| op == "blueprint.unconstrain") {
                                failures.push(format!(
                                    "BASE_GUARD_WEAKENED: constraint `{}` from `{raw_base}` was removed or modified without an approved human escalation",
                                    bc.id
                                ));
                            }
                        }
                    }
                }
            }
        }
    }

    let ok = failures.is_empty();
    Ok(json!({
        "ok": ok,
        "checked_files": checked_files,
        "base": base_ref,
        "failures": failures,
    }))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::init::{init, InitOptions};

    #[test]
    fn preview_first_apply_check_and_remove_cycle() {
        let dir = std::env::temp_dir().join(format!("afwe-mat-{}", crate::util::short_id("t")));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        init(&dir, InitOptions { name: Some("mat-test".into()), description: None, root: None, force: true }).unwrap();
        let engine = Engine::at(&dir);

        // 1. Preview does not touch disk
        let prev = run(&engine, MaterializeOptions::default()).unwrap();
        assert_eq!(prev["status"], "preview");
        assert!(!dir.join(MANIFEST_REL_PATH).exists());

        // 2. Apply writes files and BLAKE3 manifest
        let applied = run(
            &engine,
            MaterializeOptions {
                apply: true,
                native_tests: true,
                ..Default::default()
            },
        )
        .unwrap();
        assert_eq!(applied["status"], "applied");
        assert!(dir.join(MANIFEST_REL_PATH).exists());
        assert!(dir.join(".afwe/guardrails/generated_checks_test.sh").exists());

        // 3. Check succeeds on untampered files
        let chk = run(
            &engine,
            MaterializeOptions {
                check: true,
                ..Default::default()
            },
        )
        .unwrap();
        assert_eq!(chk["ok"], true);

        // 4. Tamper with generated file -> check fails
        std::fs::write(dir.join(".afwe/guardrails/generated_checks_test.sh"), "#!/bin/sh\necho tampered\n").unwrap();
        let chk_bad = run(
            &engine,
            MaterializeOptions {
                check: true,
                ..Default::default()
            },
        )
        .unwrap();
        assert_eq!(chk_bad["ok"], false);
        assert!(chk_bad["failures"][0].as_str().unwrap().contains("TAMPER_DETECTED"));

        // 5. Remove cleans up
        let rem = run(
            &engine,
            MaterializeOptions {
                remove: true,
                ..Default::default()
            },
        )
        .unwrap();
        assert_eq!(rem["status"], "removed");
        assert!(!dir.join(MANIFEST_REL_PATH).exists());

        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn missing_base_ref_fails_loudly_with_actionable_fetch_command() {
        let dir = std::env::temp_dir().join(format!("afwe-mat-base-{}", crate::util::short_id("t")));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        init(&dir, InitOptions { name: Some("base-test".into()), description: None, root: None, force: true }).unwrap();
        let engine = Engine::at(&dir);

        let chk = check_manifest(&engine, Some("deadbeef1234567890")).unwrap();
        assert_eq!(chk["ok"], false);
        let msg = chk["failures"][0].as_str().unwrap();
        assert!(msg.contains("BASE_REF_MISSING"));
        assert!(msg.contains("git fetch origin deadbeef1234567890 --depth=1"));

        let _ = std::fs::remove_dir_all(&dir);
    }
}
